"""NeoLoad as-code project generator.

Each LoadRunner script becomes a self-contained NeoLoad as-code project file
(<script>/default.yaml - the file name NeoLoad Web expects in an as-code project folder) with its servers, variables, user path (init / actions / end),
a population and a scenario. The same file can be opened in the NeoLoad GUI
and uploaded to NeoLoad Web, so one output serves both.
"""
from __future__ import annotations

import os
import shutil
from datetime import datetime
from typing import List

from . import __version__
from .jstranslate import LR_SHIM_JS
from .model import ScriptModel
from .yamlout import dump


def build_project(m: ScriptModel, users: int = 1, duration: str = "5m") -> dict:
    up_name = m.name
    user_path: dict = {"name": up_name}
    for section in ("init", "actions", "end"):
        steps = m.sections[section]
        if steps or section == "actions":
            user_path[section] = {"steps": steps or [{"delay": "0s"}]}
    servers = []
    for (scheme, host, port), name in m.servers.items():
        srv = {"name": name, "host": host, "scheme": scheme.upper()}
        if port:
            srv["port"] = port
        servers.append(srv)
    project: dict = {"name": m.name}
    if servers:
        project["servers"] = servers
    if m.variables:
        project["variables"] = m.variables
    project["user_paths"] = [user_path]
    project["populations"] = [{"name": f"{m.name}_population",
                               "user_paths": [{"name": up_name, "distribution": "100%"}]}]
    project["scenarios"] = [{"name": f"{m.name}_scenario",
                             "populations": [{"name": f"{m.name}_population",
                                              "constant_load": {"users": users, "duration": duration}}]}]
    return project


def write_project(m: ScriptModel, out_dir: str, source: str, users: int = 1, duration: str = "5m") -> List[str]:
    target = os.path.join(out_dir, m.name)
    os.makedirs(target, exist_ok=True)
    written = []
    header = (f"NeoLoad as-code project generated by lr2nl {__version__} on {datetime.now():%Y-%m-%d %H:%M}\n"
              f"Source LoadRunner script: {source}\n"
              "Lines starting with '[LR ...]' mark LoadRunner constructs that need manual review.\n"
              "Validate with: neoload validate default.yaml")
    yaml_path = os.path.join(target, "default.yaml")
    with open(yaml_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(dump(build_project(m, users, duration), header))
    written.append(yaml_path)
    if m.js_chunks:
        js_dir = os.path.join(target, "custom_js")
        os.makedirs(js_dir, exist_ok=True)
        js_path = os.path.join(js_dir, f"{m.name}.js")
        with open(js_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(f"// JavaScript translated from LoadRunner C code of '{m.name}' by lr2nl.\n"
                     "// Paste the shim plus the needed blocks into NeoLoad JavaScript actions\n"
                     "// (or a shared JS library) at the positions marked '[LR ...]' in the YAML.\n\n")
            fh.write(LR_SHIM_JS + "\n")
            fh.write("\n".join(m.js_chunks))
        written.append(js_path)
    for src, rel in m.data_files:
        dst = os.path.join(target, *rel.split("/"))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
        written.append(dst)
    return written


def write_neoload_commands(out_dir: str, yaml_files: List[str]) -> List[str]:
    """Helper scripts to validate every project and push one to NeoLoad Web with the NeoLoad CLI."""
    rel = [os.path.relpath(p, out_dir) for p in yaml_files]
    ps = ["# Generated by lr2nl. Requires the NeoLoad CLI: pip install neoload",
          "# Set $env:NLW_TOKEN (NeoLoad Web API token) and optionally $env:NLW_URL before running.",
          "param([string]$Project = '', [string]$Zone = 'defaultzone', [int]$Lgs = 1)",
          "$ErrorActionPreference = 'Stop'",
          "Set-Location $PSScriptRoot",
          "$projects = @(" + ", ".join(f"'{r}'" for r in rel) + ")",
          "foreach ($p in $projects) { Write-Host \"validate $p\"; neoload validate $p }",
          "if ($Project -eq '') { Write-Host 'Validation done. Pass -Project <file> to run one on NeoLoad Web.'; exit 0 }",
          "if ($env:NLW_URL) { neoload login --url $env:NLW_URL $env:NLW_TOKEN } else { neoload login $env:NLW_TOKEN }",
          "$name = Split-Path (Split-Path $Project) -Leaf",
          "neoload test-settings --zone $Zone --lgs $Lgs --scenario \"${name}_scenario\" createorpatch \"LR2NL_$name\"",
          "neoload project --path (Split-Path $Project) upload",
          "neoload run"]
    sh = ["#!/usr/bin/env bash",
          "# Generated by lr2nl. Requires the NeoLoad CLI: pip install neoload",
          "# export NLW_TOKEN=<NeoLoad Web API token> [NLW_URL=<api url>]; ./neoload_commands.sh [<script>/default.yaml] [zone]",
          "set -euo pipefail",
          "cd \"$(dirname \"$0\")\"",
          "for p in " + " ".join(f"'{r.replace(os.sep, '/')}'" for r in rel) + "; do echo \"validate $p\"; neoload validate \"$p\"; done",
          "[ -z \"${1:-}\" ] && { echo 'Validation done. Pass a project file to run it on NeoLoad Web.'; exit 0; }",
          "if [ -n \"${NLW_URL:-}\" ]; then neoload login --url \"$NLW_URL\" \"$NLW_TOKEN\"; else neoload login \"$NLW_TOKEN\"; fi",
          "name=$(basename \"$(dirname \"$1\")\")",
          "neoload test-settings --zone \"${2:-defaultzone}\" --lgs 1 --scenario \"${name}_scenario\" createorpatch \"LR2NL_${name}\"",
          "neoload project --path \"$(dirname \"$1\")\" upload",
          "neoload run"]
    paths = []
    for fname, lines in (("neoload_commands.ps1", ps), ("neoload_commands.sh", sh)):
        path = os.path.join(out_dir, fname)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(lines) + "\n")
        paths.append(path)
    return paths
